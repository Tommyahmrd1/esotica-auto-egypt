import fs from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import {fileURLToPath} from "node:url";

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const ORIGIN="https://esoticaegypt.com";
const GENERATED="<!-- Generated by scripts/build-english.mjs. Edit the source page or translation dictionary, then rebuild. -->\n";
const ARABIC=/[\u0600-\u06ff\u0750-\u077f\u08a0-\u08ff]/;
const VOID=new Set("area base br col embed hr img input link meta param source track wbr".split(" "));
const RAW=new Set(["script","style"]);
const TRANSLATABLE_ATTRIBUTES=new Set(["alt","title","aria-label","placeholder"]);
const ENTITIES={amp:"&",lt:"<",gt:">",quot:'"',apos:"'",nbsp:"\u00a0",copy:"©",reg:"®",ndash:"–",mdash:"—",hellip:"…"};
const normalize=value=>String(value).replace(/\s+/g," ").trim();
export const hasArabic=value=>ARABIC.test(value);
export function decodeHTML(value){
  return String(value).replace(/&(#x[\da-f]+|#\d+|[a-z]+);/gi,(entity,key)=>{
    if(key[0]==="#"){
      const number=key[1].toLowerCase()==="x"?parseInt(key.slice(2),16):parseInt(key.slice(1),10);
      return number>0&&number<=0x10ffff?String.fromCodePoint(number):"\ufffd";
    }
    return ENTITIES[key.toLowerCase()]??entity;
  });
}
const escapeText=value=>String(value).replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;");
const escapeAttribute=value=>escapeText(value).replace(/"/g,"&quot;");

// A small HTML tokenizer/tree for this site's authored static pages. Raw script
// and style blocks are never parsed as markup, and quoted > characters are safe.
export function parseHTML(source){
  const root={tag:null,children:[]},stack=[root];
  let index=0;
  while(index<source.length){
    const parent=stack.at(-1);
    if(RAW.has(parent.tag)){
      const close=new RegExp(`</${parent.tag}\\s*>`,"ig");close.lastIndex=index;
      const match=close.exec(source);
      if(!match)throw new Error(`Unclosed ${parent.tag} element`);
      parent.children.push({raw:source.slice(index,match.index)});index=close.lastIndex;stack.pop();continue;
    }
    if(source.startsWith("<!--",index)){
      const end=source.indexOf("-->",index+4);if(end<0)throw new Error("Unclosed HTML comment");
      parent.children.push({raw:source.slice(index,end+3)});index=end+3;continue;
    }
    if(source[index]!=="<"){
      const next=source.indexOf("<",index),end=next<0?source.length:next;
      parent.children.push({text:decodeHTML(source.slice(index,end))});index=end;continue;
    }
    let end=index+1,quote="";
    for(;end<source.length;end++){
      const character=source[end];
      if(quote){if(character===quote)quote=""}
      else if(character==='"'||character==="'")quote=character;
      else if(character===">")break;
    }
    if(end>=source.length)throw new Error("Unclosed HTML tag");
    const token=source.slice(index,end+1);index=end+1;
    if(/^<!|^<\?/.test(token)){parent.children.push({raw:token});continue}
    const closing=token.match(/^<\/\s*([\w:-]+)/);
    if(closing){
      const tag=closing[1].toLowerCase(),position=stack.findLastIndex(node=>node.tag===tag);
      if(position<1)throw new Error(`Unexpected closing tag ${tag}`);
      stack.length=position;continue;
    }
    const opening=token.match(/^<\s*([\w:-]+)/);if(!opening)throw new Error(`Invalid markup ${token}`);
    const tag=opening[1].toLowerCase(),attrs={};
    const attributes=token.slice(opening[0].length).replace(/\/?\s*>$/,"");
    for(const match of attributes.matchAll(/([^\s=/>]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?/g)){
      attrs[match[1].toLowerCase()]=match[2]!==undefined||match[3]!==undefined||match[4]!==undefined?decodeHTML(match[2]??match[3]??match[4]):null;
    }
    const node={tag,attrs,children:[],selfClosing:/\/\s*>$/.test(token)};parent.children.push(node);
    if(!VOID.has(tag)&&!node.selfClosing)stack.push(node);
  }
  if(stack.length!==1)throw new Error(`Unclosed HTML element ${stack.at(-1).tag}`);
  return root;
}
export function serializeHTML(node){
  if(node.raw!==undefined)return node.raw;
  if(node.text!==undefined)return escapeText(node.text);
  const body=node.children.map(serializeHTML).join("");if(!node.tag)return body;
  const attrs=Object.entries(node.attrs).map(([name,value])=>value===null?` ${name}`:` ${name}="${escapeAttribute(value)}"`).join("");
  if(VOID.has(node.tag))return `<${node.tag}${attrs}>`;
  if(node.selfClosing)return `<${node.tag}${attrs}/>`;
  return `<${node.tag}${attrs}>${body}</${node.tag}>`;
}
export function walk(node,visit){visit(node);for(const child of node.children||[])walk(child,visit)}
const content=node=>(node.children||[]).map(child=>child.text??child.raw??content(child)).join("");

export async function loadTranslations(rootDir=ROOT){
  const source=await fs.readFile(path.join(rootDir,"site.js"),"utf8");
  const start=source.indexOf("const EN="),end=source.indexOf("const AR=",start);
  if(start<0||end<0)throw new Error("Cannot locate the approved site.js translation dictionary");
  const dictionary=vm.runInNewContext(`${source.slice(start,end)}\nEN`,Object.create(null),{timeout:1000});
  const metadataSource=source.match(/const PAGE_EN_META=(\{[\s\S]*?\n\});/);
  if(!metadataSource)throw new Error("Cannot locate English page metadata");
  const metadata=vm.runInNewContext(`(${metadataSource[1]})`,Object.create(null),{timeout:1000});
  const extras=JSON.parse(await fs.readFile(path.join(rootDir,"scripts/english-translations.json"),"utf8"));
  const placeholdersSource=source.match(/const AR_PLACEHOLDERS=(\{[^\n]+\});/);
  const placeholders=placeholdersSource?vm.runInNewContext(`(${placeholdersSource[1]})`,Object.create(null),{timeout:1000}):{};
  const translations=new Map(Object.entries({...dictionary,...placeholders,...extras}).map(([ar,en])=>[normalize(ar),en]));
  return {translations,metadata};
}

export function englishURL(value,publicRoutes){
  if(!value||/^(?:#|\/\/|mailto:|tel:|data:|javascript:)/i.test(value))return value;
  let url;try{url=new URL(value,ORIGIN)}catch{return value}
  if(url.origin!==ORIGIN)return value;
  const base=url.pathname.replace(/^\/en(?=\/|$)/,"").replace(/\.html$/,"").replace(/\/$/,"")||"/";
  if(!publicRoutes.has(base))return value;
  url.pathname=base==="/"?"/en":`/en${base}`;
  return value.startsWith("http")?url.href:`${url.pathname}${url.search}${url.hash}`;
}

export function translateDocument(source,route,{translations,metadata},missing=new Map()){
  const tree=parseHTML(source),publicRoutes=new Set(Object.keys(metadata));
  const entry=metadata[route];if(!entry)throw new Error(`No English metadata for ${route}`);
  const [title,description]=entry,canonical=englishURL(`${ORIGIN}${route}`,publicRoutes);
  function translate(value,context){
    if(!hasArabic(value))return value;
    const found=translations.get(normalize(value));
    if(found){
      if(hasArabic(found))throw new Error(`English translation contains Arabic: ${found}`);
      return value.replace(/^\s*[\s\S]*?\S\s*$/u,()=>`${value.match(/^\s*/)[0]}${found}${value.match(/\s*$/)[0]}`);
    }
    const text=normalize(value);if(!missing.has(text))missing.set(text,new Set());missing.get(text).add(`${route} (${context})`);
    return value;
  }
  function translateStructured(value,key=""){
    // Keep entity identifiers, brand aliases and technical business facts stable.
    if(["@id","alternateName","geo","telephone","hasMap","openingHoursSpecification","openingHours","opens","closes","dayOfWeek"].includes(key))return value;
    if(Array.isArray(value))return value.map(item=>translateStructured(item,key));
    if(value&&typeof value==="object")return Object.fromEntries(Object.entries(value).map(([name,item])=>[name,translateStructured(item,name)]));
    if(typeof value!=="string")return value;
    if(["url","item"].includes(key))return englishURL(value,publicRoutes);
    return translate(value,`structured data: ${key}`);
  }
  function visit(node){
    if(node.text!==undefined){node.text=translate(node.text,"text");return}
    if(!node.tag){for(const child of node.children||[])visit(child);return}
    if(node.tag==="html"){
      node.attrs.lang="en";node.attrs.dir="ltr";node.attrs["data-prerendered-language"]="en";
      if(node.attrs.class)node.attrs.class=node.attrs.class.split(/\s+/).filter(name=>name!=="language-pending").join(" ");
    }
    for(const name of TRANSLATABLE_ATTRIBUTES)if(node.attrs[name])node.attrs[name]=translate(node.attrs[name],`${node.tag}[${name}]`);
    if(node.tag==="a"&&node.attrs.href)node.attrs.href=englishURL(node.attrs.href,publicRoutes);
    if(node.tag==="title"){node.children=[{text:title}];return}
    if(node.tag==="meta"){
      const name=node.attrs.name||node.attrs.property;
      if(["description","og:description","twitter:description"].includes(name))node.attrs.content=description;
      if(["og:title","twitter:title"].includes(name))node.attrs.content=title;
      if(name==="og:url")node.attrs.content=canonical;
      if(name==="og:locale")node.attrs.content="en_US";
      if(name==="og:locale:alternate")node.attrs.content="ar_EG";
    }
    if(node.tag==="link"&&node.attrs.rel==="canonical")node.attrs.href=canonical;
    if(node.tag==="script"){
      const text=content(node);
      if(node.attrs.type==="application/ld+json")node.children=[{raw:JSON.stringify(translateStructured(JSON.parse(text))).replace(/</g,"\\u003c")}];
      else if(!node.attrs.src&&/esotica-language|language-pending|document\.documentElement\.(?:lang|dir)\s*=/.test(text)){
        node.children=[{raw:'document.documentElement.lang="en";document.documentElement.dir="ltr";document.documentElement.classList.remove("language-pending");'}];
      }
      return;
    }
    if(node.tag==="style")return;
    // An option without value submits its text, so preserve that implicit value
    // before translating its visible label.
    if(node.tag==="option"&&!Object.hasOwn(node.attrs,"value"))node.attrs.value=content(node);
    if(node.attrs["data-en"]!==undefined&&node.attrs["data-ar"]!==undefined){
      if(hasArabic(node.attrs["data-en"]))throw new Error(`${route}: data-en contains Arabic`);
      node.children=[{text:node.attrs["data-en"]}];return;
    }
    for(const child of node.children)visit(child);
  }
  visit(tree);
  return GENERATED+serializeHTML(tree).replace(/\r\n/g,"\n").trimEnd()+"\n";
}

export async function buildEnglish({rootDir=ROOT,check=false,allowMissing=false}={}){
  const resources=await loadTranslations(rootDir),missing=new Map(),outputs=[],pages=[];
  for(const route of Object.keys(resources.metadata).sort()){
    const file=route==="/"?"index.html":`${route.slice(1)}.html`;
    const source=await fs.readFile(path.join(rootDir,file),"utf8");
    // Brand pages already carry approved bilingual copy, also reused by their
    // matching FAQ structured data. Share it before translating any page.
    walk(parseHTML(source),node=>{
      if(node.attrs?.["data-ar"]&&node.attrs?.["data-en"])resources.translations.set(normalize(node.attrs["data-ar"]),node.attrs["data-en"]);
    });
    pages.push({route,file,source});
  }
  for(const {route,file,source} of pages){
    outputs.push({route,file:path.posix.join("en",file),html:translateDocument(source,route,resources,missing)});
  }
  if(missing.size&&!allowMissing){
    const details=[...missing].map(([text,locations])=>`${JSON.stringify(text)}\n  ${[...locations].join(", ")}`).join("\n");
    throw new Error(`Missing ${missing.size} English translations:\n${details}`);
  }
  if(allowMissing)return {outputs,missing,resources};
  const stale=[];
  for(const output of outputs){
    const file=path.join(rootDir,output.file);
    if(check){
      const existing=await fs.readFile(file,"utf8").catch(error=>{if(error.code==="ENOENT")return null;throw error});
      if(existing!==output.html)stale.push(output.file);
    }else{await fs.mkdir(path.dirname(file),{recursive:true});await fs.writeFile(file,output.html,"utf8")}
  }
  async function checkUnexpected(directory){
    for(const entry of await fs.readdir(directory,{withFileTypes:true}).catch(error=>{if(error.code==="ENOENT")return [];throw error})){
      const file=path.join(directory,entry.name);
      if(entry.isDirectory())await checkUnexpected(file);
      else if(entry.name.endsWith(".html")&&!outputs.some(output=>path.join(rootDir,output.file)===file))stale.push(path.relative(rootDir,file));
    }
  }
  await checkUnexpected(path.join(rootDir,"en"));
  if(stale.length)throw new Error(`English pages are missing, stale or unexpected: ${stale.join(", ")}. Run node scripts/build-english.mjs.`);
  return {outputs,resources};
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  try{
    const result=await buildEnglish({check:process.argv.includes("--check")});
    console.log(`English pages ${process.argv.includes("--check")?"verified":"generated"}: ${result.outputs.length}.`);
  }catch(error){console.error(error.message);process.exitCode=1}
}
